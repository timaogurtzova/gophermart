// Package handler содержит HTTP-обработчики API «Гофермарт».
//
// Обработчики отвечают только за транспортный слой: чтение JSON или text/plain
// тела запроса, проверку формата запроса, получение пользователя из контекста,
// вызов сервисного слоя и преобразование доменных ошибок в HTTP-коды из ТЗ.
//
// Основные коды ответов из ТЗ: 200 для успешной обработки, 202 для принятого в
// обработку заказа, 204 при отсутствии данных для ответа, 400 при неверном
// формате запроса, 401 для неавторизованного пользователя, 402 при
// недостаточном балансе, 409 при конфликте логина или номера заказа, 422 при
// неверном номере заказа и 500 при внутренней ошибке сервера.
